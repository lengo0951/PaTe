import AppKit
import ApplicationServices
import Carbon

public enum CredentialPasteMode {
    case defaultSecret
    case usernameOnly
    case autoFillTab
}

@MainActor
public class PasteSimulator {
    public static let shared = PasteSimulator()
    
    public var lastFrontmostApplication: NSRunningApplication?
    private var secretCleanupWorkItem: DispatchWorkItem?
    
    private init() {
        // Capture current external frontmost app at launch
        if let front = NSWorkspace.shared.frontmostApplication,
           front.bundleIdentifier != Bundle.main.bundleIdentifier {
            lastFrontmostApplication = front
        }
        
        // Continuously track the user's active external application so we NEVER lose paste target!
        NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification,
            object: nil,
            queue: .main
        ) { [weak self] notification in
            guard let app = notification.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication,
                  app.bundleIdentifier != Bundle.main.bundleIdentifier,
                  app.activationPolicy == .regular else {
                return
            }
            Task { @MainActor in
                self?.lastFrontmostApplication = app
            }
        }
    }
    
    public var isAccessibilityGranted: Bool {
        return AXIsProcessTrusted()
    }
    
    public func promptAccessibilityAccess() {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }
    
    public func pasteItem(
        _ item: ClipboardItem,
        asPlainText: Bool = false,
        credentialMode: CredentialPasteMode = .defaultSecret,
        store: HistoryStore,
        completion: (() -> Void)? = nil
    ) {
        let pasteboard = NSPasteboard.general
        
        // Special handling for Credential Vault auto-fill (Username -> Tab -> Password)
        if item.contentType == .credential && credentialMode == .autoFillTab {
            let username = item.credentialUsername ?? ""
            let secret = CredentialVault.shared.getSecret(for: item.id) ?? ""
            
            SoundManager.shared.playPaste()
            completion?()
            
            deliverFocusToTargetApp { [weak self] in
                guard let self = self else { return }
                // Step 1: Paste Username
                if !username.isEmpty {
                    self.writeStringToPasteboard(username, concealed: false)
                    if self.isAccessibilityGranted {
                        self.simulateCmdV()
                    }
                }
                // Step 2: Press Tab & Paste Secret
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.065) { [weak self] in
                    guard let self = self else { return }
                    if self.isAccessibilityGranted {
                        self.simulateKey(keyCode: 0x30) // kVK_Tab
                    }
                    DispatchQueue.main.asyncAfter(deadline: .now() + 0.045) { [weak self] in
                        guard let self = self else { return }
                        if !secret.isEmpty {
                            let expectedCount = self.writeStringToPasteboard(secret, concealed: true)
                            if self.isAccessibilityGranted {
                                self.simulateCmdV()
                            }
                            self.scheduleClipboardAutoClear(expectedChangeCount: expectedCount)
                        }
                    }
                }
            }
            return
        }
        
        // 1. Copy item to NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        var scheduleAutoClearCount: Int? = nil
        
        switch item.contentType {
        case .credential:
            if credentialMode == .usernameOnly {
                if let username = item.credentialUsername {
                    pasteboard.setString(username, forType: .string)
                }
            } else {
                // Default Enter / Double-Click pastes the decrypted Vault password
                let secret = CredentialVault.shared.getSecret(for: item.id) ?? item.textValue ?? ""
                pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
                pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
                pasteboard.setString(secret, forType: .string)
                scheduleAutoClearCount = pasteboard.changeCount
            }
            
        case .image:
            if let imgName = item.imageFileName,
               let image = store.loadImage(fileName: imgName),
               let tiff = image.tiffRepresentation {
                pasteboard.setData(tiff, forType: .tiff)
            }
            
        case .file:
            if let paths = item.filePaths {
                let urls = paths.map { URL(fileURLWithPath: $0) as NSPasteboardWriting }
                pasteboard.writeObjects(urls)
            }
            
        default:
            if asPlainText || item.rtfData == nil {
                if let text = item.textValue {
                    pasteboard.setString(text, forType: .string)
                }
            } else {
                if let rtf = item.rtfData {
                    pasteboard.setData(rtf, forType: .rtf)
                }
                if let text = item.textValue {
                    pasteboard.setString(text, forType: .string)
                }
            }
        }
        
        // 2. Play paste sound & dismiss UI
        SoundManager.shared.playPaste()
        completion?()
        
        // 3.Schedule auto-clear if secret was pasted
        if let count = scheduleAutoClearCount {
            scheduleClipboardAutoClear(expectedChangeCount: count)
        }
        
        // 4. Verify focus handoff to target app and synthesize Cmd+V deterministically
        deliverFocusToTargetApp { [weak self] in
            guard let self = self else { return }
            if self.isAccessibilityGranted {
                self.simulateCmdV()
            } else {
                self.promptAccessibilityAccess()
            }
        }
    }
    
    @discardableResult
    private func writeStringToPasteboard(_ value: String, concealed: Bool) -> Int {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        if concealed {
            pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
            pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        }
        pb.setString(value, forType: .string)
        return pb.changeCount
    }
    
    private func scheduleClipboardAutoClear(expectedChangeCount: Int) {
        secretCleanupWorkItem?.cancel()
        let work = DispatchWorkItem {
            if NSPasteboard.general.changeCount == expectedChangeCount {
                NSPasteboard.general.clearContents()
            }
        }
        secretCleanupWorkItem = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 15.0, execute: work)
    }
    
    /// Deterministic focus verification: if target app is already active (non-activating HUD),
    /// fires in 12ms; if app switch is needed, waits until WindowServer confirms `targetApp.isActive`.
    private func deliverFocusToTargetApp(ready: @escaping @MainActor () -> Void) {
        guard let targetApp = self.lastFrontmostApplication, !targetApp.isTerminated else {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.015) {
                ready()
            }
            return
        }
        
        if targetApp.isActive && NSWorkspace.shared.frontmostApplication?.processIdentifier == targetApp.processIdentifier {
            // Target app already owns active focus! Just wait 12ms for NSPanel.orderOut to flush.
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.012) {
                ready()
            }
            return
        }
        
        targetApp.activate(options: [.activateIgnoringOtherApps])
        waitForTargetAppActivation(targetApp: targetApp, attemptsRemaining: 16, ready: ready)
    }
    
    private func waitForTargetAppActivation(
        targetApp: NSRunningApplication,
        attemptsRemaining: Int,
        ready: @escaping @MainActor () -> Void
    ) {
        if targetApp.isActive || attemptsRemaining <= 0 {
            // Extra 8ms settle for firstResponder text field inside target app
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.008) {
                ready()
            }
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.008) { [weak self] in
            self?.waitForTargetAppActivation(
                targetApp: targetApp,
                attemptsRemaining: attemptsRemaining - 1,
                ready: ready
            )
        }
    }
    
    private static let eventSource = CGEventSource(stateID: .hidSystemState)
    
    private func simulateCmdV() {
        let vKeyCode: CGKeyCode = 0x09 // kVK_ANSI_V
        guard let keyDown = CGEvent(keyboardEventSource: Self.eventSource, virtualKey: vKeyCode, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: Self.eventSource, virtualKey: vKeyCode, keyDown: false) else {
            return
        }
        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand
        keyDown.post(tap: .cghidEventTap)
        keyUp.post(tap: .cghidEventTap)
    }
    
    private func simulateKey(keyCode: CGKeyCode, flags: CGEventFlags = []) {
        guard let keyDown = CGEvent(keyboardEventSource: Self.eventSource, virtualKey: keyCode, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: Self.eventSource, virtualKey: keyCode, keyDown: false) else {
            return
        }
        keyDown.flags = flags
        keyUp.flags = flags
        keyDown.post(tap: .cghidEventTap)
        keyUp.post(tap: .cghidEventTap)
    }
}
