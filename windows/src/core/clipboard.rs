use crate::core::types::ContentType;

pub const AUTO_GENERATED_FORMAT_NAME: &str = "PasteFlowAutoGenerated";
pub const CF_UNICODETEXT: u32 = 13;

pub struct ClipboardEvent {
    pub text: String,
    pub content_type: ContentType,
    pub source_app: Option<String>,
}

#[cfg(windows)]
pub mod win32 {
    use super::*;
    use std::sync::atomic::{AtomicU32, Ordering};
    use windows::Win32::Foundation::*;
    use windows::Win32::System::DataExchange::*;
    use windows::Win32::System::Memory::*;
    use windows::core::*;

    static AUTO_GEN_FMT_ID: AtomicU32 = AtomicU32::new(0);

    pub fn get_auto_generated_format_id() -> u32 {
        let cached = AUTO_GEN_FMT_ID.load(Ordering::Relaxed);
        if cached != 0 {
            return cached;
        }
        unsafe {
            let wide: Vec<u16> = AUTO_GENERATED_FORMAT_NAME.encode_utf16().chain(std::iter::once(0)).collect();
            let id = RegisterClipboardFormatW(PCWSTR(wide.as_ptr()));
            AUTO_GEN_FMT_ID.store(id, Ordering::Relaxed);
            id
        }
    }

    pub fn is_self_paste(hwnd: HWND) -> bool {
        unsafe {
            if OpenClipboard(hwnd).is_ok() {
                let fmt_id = get_auto_generated_format_id();
                let is_self = IsClipboardFormatAvailable(fmt_id).is_ok();
                let _ = CloseClipboard();
                return is_self;
            }
        }
        false
    }

    pub fn read_clipboard_text(hwnd: HWND) -> Option<String> {
        unsafe {
            if OpenClipboard(hwnd).is_err() {
                return None;
            }

            // Check self paste
            let self_fmt = get_auto_generated_format_id();
            if IsClipboardFormatAvailable(self_fmt).is_ok() {
                let _ = CloseClipboard();
                return None;
            }

            let mut result = None;
            if IsClipboardFormatAvailable(CF_UNICODETEXT).is_ok() {
                if let Ok(handle) = GetClipboardData(CF_UNICODETEXT) {
                    let ptr = GlobalLock(HGLOBAL(handle.0));
                    if !ptr.is_null() {
                        let wide_slice = std::slice::from_raw_parts(ptr as *const u16, 1024 * 1024);
                        if let Some(len) = wide_slice.iter().position(|&c| c == 0) {
                            result = Some(String::from_utf16_lossy(&wide_slice[..len]));
                        }
                        let _ = GlobalUnlock(HGLOBAL(handle.0));
                    }
                }
            }

            let _ = CloseClipboard();
            result
        }
    }
}
