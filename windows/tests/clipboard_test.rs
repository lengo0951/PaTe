use pate_windows::core::types::ContentType;
use pate_windows::core::clipboard::AUTO_GENERATED_FORMAT_NAME;

#[test]
fn test_classify_plain_text() {
    let input = "Hello, this is a standard text message.";
    assert_eq!(ContentType::classify(input), ContentType::Text);
}

#[test]
fn test_classify_url() {
    assert_eq!(ContentType::classify("https://github.com/lengo0951/PasteFlow"), ContentType::Link);
    assert_eq!(ContentType::classify("http://localhost:8006"), ContentType::Link);
    assert_eq!(ContentType::classify("www.google.com"), ContentType::Link);
}

#[test]
fn test_classify_hex_color() {
    assert_eq!(ContentType::classify("#FFF"), ContentType::Color);
    assert_eq!(ContentType::classify("#0A84FF"), ContentType::Color);
    assert_eq!(ContentType::classify("#12345678"), ContentType::Color);
    assert_ne!(ContentType::classify("#NOT_HEX"), ContentType::Color);
}

#[test]
fn test_classify_code_snippet() {
    let rust_code = "fn main() {\n    println!(\"Hello\");\n}";
    assert_eq!(ContentType::classify(rust_code), ContentType::Code);

    let js_code = "const x = 42;\nfunction test() { return x; }";
    assert_eq!(ContentType::classify(js_code), ContentType::Code);

    let sql_code = "SELECT id, name FROM users WHERE active = 1;";
    assert_eq!(ContentType::classify(sql_code), ContentType::Code);
}

#[test]
fn test_self_paste_suppression_tag() {
    assert_eq!(AUTO_GENERATED_FORMAT_NAME, "PATEAutoGenerated");
}
